'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createFixture}=require('./native-project-runtime.cjs');
const {createNativeProjectRuntime}=require('../src/modules/native-project-runtime.cjs');

async function run() {
  const f=createFixture(),{runtime,store,api}=f;
  const post=(name,args)=>api('/api/native-conversations/'+name,'POST',args);
  const list=async(project='p1')=>(await api('/api/native-conversations/list?project_id='+project)).value;
  const get=async row=>(await api('/api/native-conversations/context?project_id='+row.project_id+'&kind='+row.kind+'&conversation_id='+row.conversation_id)).value;
  const auth=row=>({project_id:row.project_id,kind:row.kind,conversation_id:row.conversation_id,relay_id:'relay-leader',host_id:'local',expected_revision:row.revision,draft_generation:row.generation});
  const tool=(row,name,args={},callId)=>post('tool',{relay_id:'relay-leader',host_id:'local',thread_id:row.thread_id,call_id:callId || name+'-'+Math.random(),name:'better_codex_'+name,arguments:args});
  async function send(row,threadId) {
    const context=await get(row), args={...auth(row),expected_revision:context.expected_revision,request_id:'send-'+threadId};
    const prepared=(await post('prepare',args)).value;
    assert.equal(prepared.operation.conversation_id,row.conversation_id);
    await post('bind',{...args,thread_id:threadId,checkpoint:'allocated'});
    const bound=(await post('bind',{...args,thread_id:threadId,checkpoint:'bound'})).value;
    assert.equal(bound.binding.conversation_id,row.conversation_id);
    await post('receipt',{...args,thread_id:threadId,turn_id:'turn-'+threadId,status:'accepted'});
    runtime.handleProjectEvent('turn/completed',{threadId,turn:{id:'turn-'+threadId,status:'completed'}});
    return {...row,thread_id:threadId,revision:1};
  }
  try {
    assert.deepEqual((await list()).conversations,[]);
    await api('/api/native-conversations/context?project_id=p1&kind=charter');
    assert.equal(store.db.prepare('SELECT COUNT(*) AS count FROM project_native_conversations').get().count,0,'reading empty projects does not pre-create conversations');
    const first=(await post('create',{project_id:'p1',kind:'charter'})).value.conversation;
    const second=(await post('create',{project_id:'p1',kind:'charter',title:'接口边界讨论'})).value.conversation;
    assert.notEqual(first.conversation_id,second.conversation_id);assert.equal(second.title,'接口边界讨论');
    assert.equal(second.selected,true);assert.equal(second.thread_id,null);
    assert.equal(store.db.prepare('SELECT COUNT(*) AS count FROM native_conversation_operations').get().count,0,'metadata create does not prepare, allocate, send or queue');
    assert.equal(runtime.planning.listPendingCommands().length,0);
    await assert.rejects(post('select',{project_id:'p2',conversation_id:first.conversation_id}),/conversation_project_mismatch/);
    await assert.rejects(api('/api/native-conversations/context?project_id=p1&kind=planning&conversation_id='+first.conversation_id),/conversation_kind_mismatch/);
    await post('select',{project_id:'p1',conversation_id:first.conversation_id});
    assert.equal((await list()).selected_conversation_id,first.conversation_id);
    assert.equal((await get(first)).target.conversation_id,first.conversation_id);
    const request={...auth(first),request_id:'reserved-first'};
    await post('prepare',request);
    await assert.rejects(post('select',{project_id:'p1',conversation_id:second.conversation_id}),/native_conversation_busy/);
    await assert.rejects(post('create',{project_id:'p1',kind:'charter'}),/native_conversation_busy/);
    await assert.rejects(post('bind',{...request,conversation_id:second.conversation_id,thread_id:'first-thread',checkpoint:'allocated'}),/native_operation_scope_mismatch/);
    await post('bind',{...request,thread_id:'first-thread',checkpoint:'allocated'});
    await post('bind',{...request,thread_id:'first-thread',checkpoint:'bound'});
    await post('receipt',{...request,thread_id:'first-thread',turn_id:'first-turn',status:'accepted'});
    await assert.rejects(post('select',{project_id:'p1',conversation_id:second.conversation_id}),/native_conversation_busy/);
    runtime.handleProjectEvent('turn/completed',{threadId:'first-thread',turn:{id:'first-turn',status:'completed'}});
    const boundFirst={...first,thread_id:'first-thread',revision:1};
    await post('select',{project_id:'p1',conversation_id:second.conversation_id});
    const boundSecond=await send(second,'second-thread');
    assert.equal(runtime.planning.getSession('p1','charter').thread_id,'second-thread');
    const charterArgs=f.charterArgs('p1','first-thread');delete charterArgs.project_id;delete charterArgs.thread_id;
    const saved=(await tool(boundFirst,'project_charter_save',charterArgs)).value;assert.equal(saved.revision,1,'old unselected native threads remain trusted for shared project documents');
    await assert.rejects(tool(boundSecond,'project_charter_save',charterArgs),/version_conflict/);
    await tool(boundSecond,'project_charter_save',{...charterArgs,expected_revision:1});
    assert.equal(runtime.planning.getCharter('p1').revision,2);
    f.userMessage('first-thread','first-confirm','确认总纲');
    const evidence=(await tool(boundFirst,'project_context_read')).value;
    assert.equal(evidence.confirmation_candidates[0].event_id,'first-confirm');
    await assert.rejects(tool(boundSecond,'project_charter_confirm',{expected_revision:2,message_id:'first-confirm'}),/explicit_user_confirmation_required/);
    await tool(boundFirst,'project_charter_confirm',{expected_revision:2,message_id:'first-confirm'});
    assert.equal(runtime.planning.getCharter('p1').status,'confirmed');
    const planA=(await post('create',{project_id:'p1',kind:'planning'})).value.conversation;
    const boundPlanA=await send(planA,'plan-a-thread');
    const planB=(await post('create',{project_id:'p1',kind:'planning'})).value.conversation;
    const boundPlanB=await send(planB,'plan-b-thread');
    const planArgs={expected_revision:0,charter_revision:3,items:[f.item()]};
    await tool(boundPlanA,'project_plan_save',planArgs);
    await assert.rejects(tool(boundPlanB,'project_plan_save',planArgs),/version_conflict/);
    await tool(boundPlanB,'project_plan_save',{...planArgs,expected_revision:1});
    const converted=(await tool(boundPlanA,'project_plan_convert',{expected_revision:2,item_ids:['deliver-login']})).value;
    const repeated=(await tool(boundPlanB,'project_plan_convert',{expected_revision:2,item_ids:['deliver-login']})).value;
    assert.equal(converted.items[0].issue_id,repeated.items[0].issue_id);
    assert.equal(f.state.create,1);assert.equal(f.state.dispatch,0);assert.equal(f.state.wake,0);
    const shared=(await get(boundPlanB)).context;
    assert.equal(shared.planning_links[0].issue_id,converted.items[0].issue_id);assert.equal(shared.planning_links[0].status,'backlog');
    assert.equal(shared.tasks[0].item_id,'deliver-login');
    const reset=(await post('restart',{project_id:'p1',kind:'charter',conversation_id:first.conversation_id,expected_revision:1,explicit:true})).value;
    assert.notEqual(reset.conversation_id,first.conversation_id);assert.equal(reset.thread_id,null);
    const closed=(await list()).conversations.find(row=>row.conversation_id===first.conversation_id);
    assert.equal(closed.status,'closed');assert.equal(closed.thread_id,'first-thread');
    await post('select',{project_id:'p1',conversation_id:first.conversation_id});
    const reopened=await get(first);assert.equal(reopened.thread_id,'first-thread');assert.equal(reopened.mode,'thread');
    const continued={...auth(boundFirst),request_id:'continue-history'};
    const resumed=(await post('prepare',continued)).value;assert.equal(resumed.operation.thread_id,'first-thread');
    await post('bind',{...continued,thread_id:'first-thread',checkpoint:'allocated'});await post('bind',{...continued,thread_id:'first-thread',checkpoint:'bound'});
    await post('receipt',{...continued,thread_id:'first-thread',status:'failed',error:'known no-turn fixture'});
    assert.equal(store.db.prepare('SELECT COUNT(*) AS count FROM project_charter_revisions').get().count,3,'selection/history operations preserve charter versions');
    assert(fs.readdirSync(path.join(f.home,'backups','native-conversations')).every(name=>fs.statSync(path.join(f.home,'backups','native-conversations',name)).size>0));
    store.db.prepare(`INSERT INTO project_native_sessions(project_id,kind,thread_id,owner,status,revision,created_at,updated_at)
      VALUES('p2','charter','legacy-current','native','ready',1,'2000','2000')`).run();
    store.db.prepare(`INSERT INTO native_conversation_history(id,project_id,kind,thread_id,binding_json,archived_at)
      VALUES('legacy-history','p2','planning','legacy-history-thread',?,'2001')`).run(JSON.stringify({thread_id:'legacy-history-thread',host_id:'local',revision:1,created_at:'2000'}));
    for (const [index,value] of ['','broken JSON','null','[]'].entries()) store.db.prepare(`INSERT INTO native_conversation_history(id,project_id,kind,thread_id,binding_json,archived_at)
      VALUES(?,'p2','charter',?,?,'2002')`).run('damaged-'+index,'damaged-thread-'+index,value);
    const makeRuntime=()=>createNativeProjectRuntime({store,worker:{wake(){throw Error('unexpected wake');}},home:f.home,userHome:f.userHome,codexHome:f.codexHome});
    const migrated=makeRuntime();
    const migrationRows=migrated.conversations.listConversations('p2').conversations;assert.equal(migrationRows.length,2);
    assert(migrationRows.some(row=>row.thread_id==='legacy-current'));assert(migrationRows.some(row=>row.thread_id==='legacy-history-thread'&&row.status==='closed'));
    assert.deepEqual(makeRuntime().conversations.listConversations('p2').conversations.map(row=>row.conversation_id).sort(),migrationRows.map(row=>row.conversation_id).sort(),'migration remains idempotent and retains original native threads');
    assert.equal(store.db.prepare("SELECT COUNT(*) AS count FROM native_conversation_history WHERE id LIKE 'damaged-%'").get().count,4,'damaged metadata stays preserved and cannot prevent runtime startup');
    assert.equal(f.state.dispatch,0);assert.equal(f.state.wake,0);
    console.log('PASS: multiple planning conversations, read-only listing, metadata-only creation, guarded selection, scoped allocation, trusted historical tools, shared revision/confirmation, conversion links and idempotent migration');
  } finally {f.cleanup();}
}
if(require.main===module) run().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={run};
