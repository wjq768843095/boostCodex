const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/ui/better-codex-ui.js'),'utf8');
const start=source.indexOf('    function onProjectsClick(event) {');
const end=source.indexOf('\n    function ',start+1);
const calls=[];let pending;
const convert={dataset:{planConvert:'p'},disabled:false,isConnected:true};
const ctx=vm.createContext({state:{planningContexts:{p:{plan:{revision:3,items:[{id:'A'},{id:'B'},{id:'C'}],issue_links:[{item_id:'C',issue_id:'existing'}]}}},planSelections:{p:[]}},inlineConversation:null,inlineConversationRoot:null,panel:{querySelector:()=>convert},perform:fn=>pending=fn(),api:async(url,options)=>calls.push({url,body:JSON.parse(options.body)}),loadProjects:async()=>{},loadIssues:async()=>{}});
vm.runInContext(source.slice(start,end),ctx);
const eventFor=(selector,node)=>({target:{closest:s=>s===selector?node:null}});
(async()=>{
  ctx.onProjectsClick(eventFor('[data-plan-convert]',convert));await pending;
  assert.equal(calls.length,0,'an empty selection cannot submit or default to all tasks');
  assert.equal(convert.disabled,true);
  const box={dataset:{planProject:'p',planItem:'A'},checked:true,disabled:false};
  ctx.onProjectsClick(eventFor('[data-plan-item]',box));
  assert.equal(convert.disabled,false);
  assert.deepEqual(Array.from(ctx.state.planSelections.p),['A']);
  ctx.state.planSelections.p.push('C','removed');
  ctx.onProjectsClick(eventFor('[data-plan-convert]',convert));await pending;
  assert.deepEqual(calls[0].body,{expected_revision:3,item_ids:['A']},'only the checked eligible task is sent; unchecked B and already converted C are excluded');
  assert.deepEqual(Array.from(ctx.state.planSelections.p),[]);
  box.checked=false;ctx.onProjectsClick(eventFor('[data-plan-item]',box));assert.equal(convert.disabled,true);
  box.checked=true;box.disabled=true;ctx.onProjectsClick(eventFor('[data-plan-item]',box));assert.deepEqual(Array.from(ctx.state.planSelections.p),[]);
  console.log('PASS: explicit checkbox selection, empty-submit prevention, subset-only conversion and already-converted exclusion');
})().catch(e=>{console.error(e);process.exitCode=1;});
